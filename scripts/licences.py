"""Licence inventory for the submission references (plan 15.2 / 19.3: list every package, even if open source).

Reads the real package trees, never a hand-written list:
- npm: every entry in package-lock.json (production vs development from the lockfile's `dev` flag), with the licence
  from the lockfile cross-checked against the installed node_modules/<name>/package.json;
- pipeline: every distribution installed in the pipeline virtualenv (importlib.metadata);
- native libraries bundled inside wheels (rasterio.libs, numpy.libs): names and versions from the file names; the wheels
  ship no per-library licence text, so their licences are reported as NOT VERIFIED here.

Usage: .venv/bin/python scripts/licences.py > docs/licences.md      (--check exits 1 if docs/licences.md is stale)
"""
import json, re, sys
from importlib.metadata import distributions
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def npm_rows():
    lock = json.loads((ROOT / "package-lock.json").read_text())
    rows = []
    for key, p in lock["packages"].items():
        if not key:
            continue
        name = key.split("node_modules/")[-1]
        installed = ROOT / key / "package.json"
        lic_inst = None
        if installed.exists():
            m = json.loads(installed.read_text())
            lic_inst = m.get("license") if isinstance(m.get("license"), str) else json.dumps(m.get("license"))
        lic = p.get("license") or lic_inst or "NOT STATED"
        note = "" if (lic_inst is None or lic_inst == lic) else f"installed package.json says {lic_inst}"
        if not installed.exists():
            note = "not installed on this platform (optional)" if p.get("optional") else "NOT INSTALLED"
        rows.append(("development" if p.get("dev") else "production", name, p.get("version", "?"), lic, note))
    return sorted(set(rows), key=lambda r: (r[0] != "production", r[1].lower(), r))  # full tuple: nested same-name packages sort the same every run


def pip_rows():
    rows = []
    for d in distributions():
        m = d.metadata
        lic = m.get("License-Expression") or ""
        if not lic:
            classifiers = [c.split("::")[-1].strip() for c in m.get_all("Classifier") or [] if c.startswith("License ::")]
            lic = "; ".join(classifiers) or (m.get("License") or "").strip().splitlines()[0][:60] if (m.get("License") or classifiers) else "NOT STATED"
        tooling = " (virtualenv tooling, not a pipeline dependency)" if m["Name"].lower() in {"pip", "setuptools", "wheel"} else ""
        rows.append((m["Name"] + tooling, d.version, lic or "NOT STATED"))
    return sorted(set(rows), key=lambda r: r[0].lower())


def native_rows():
    site = next((ROOT / ".venv" / "lib").glob("python*/site-packages"))
    rows = []
    for libs in sorted(site.glob("*.libs")):
        for f in sorted(libs.iterdir()):
            m = re.match(r"(lib[A-Za-z0-9_+.]*?)(?:-[0-9a-f]{8})+\.so(?:\.([\d.]+))?$", f.name)
            rows.append((libs.name.replace(".libs", ""), m.group(1) if m else f.name, (m.group(2) or "?") if m else "?"))
    return rows


def render() -> str:
    npm, pip, native = npm_rows(), pip_rows(), native_rows()
    prod = [r for r in npm if r[0] == "production"]
    out = ["# SharpWalk licence inventory", "",
           "Generated by `scripts/licences.py` from package-lock.json, node_modules and the pipeline virtualenv. "
           "Do not edit by hand; regenerate with `.venv/bin/python scripts/licences.py > docs/licences.md`.", "",
           f"- npm packages in the lockfile: {len(npm)} ({len(prod)} production, shipped in or installed with the app; "
           f"{len(npm) - len(prod)} development-only, never shipped).",
           f"- Pipeline Python distributions installed: {len(pip)}. Pipeline code runs once to prepare data; it is not shipped.",
           f"- Native libraries bundled in pipeline wheels: {len(native)} (licences not verified from installed files).", "",
           "## npm packages", "", "| Scope | Package | Version | Licence | Note |", "|---|---|---|---|---|"]
    out += [f"| {s} | {n} | {v} | {l} | {note} |" for s, n, v, l, note in npm]
    out += ["", "## Pipeline Python distributions (virtualenv)", "", "| Package | Version | Licence (metadata) |", "|---|---|---|"]
    out += [f"| {n} | {v} | {l} |" for n, v, l in pip]
    out += ["", "## Native libraries bundled in wheels", "",
            "The wheels ship no per-library licence texts, so these licences are **NOT VERIFIED** from installed files "
            "and must be checked against each upstream project before they are listed in the submission.", "",
            "| Wheel | Library | Shared-object version (from the file name; not the release number) |", "|---|---|---|"]
    out += [f"| {w} | {n} | {v} |" for w, n, v in native]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        current = (ROOT / "docs" / "licences.md").read_text() if (ROOT / "docs" / "licences.md").exists() else ""
        sys.exit(0 if current == text else 1)
    sys.stdout.write(text)
